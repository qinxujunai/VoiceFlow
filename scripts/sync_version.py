"""Generate Windows build metadata from src/version.py without executing it."""

import argparse
import ast
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]


def read_version(root=ROOT):
    tree = ast.parse((Path(root) / "src" / "version.py").read_text(encoding="utf-8"))
    values = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            name = node.targets[0].id
            if name in {"APP_VERSION", "BUILD_ID", "WINDOWS_REVISION"}:
                if name in values:
                    raise ValueError(f"duplicate version source: {name}")
                values[name] = ast.literal_eval(node.value)
    app, build, revision = (values.get(key) for key in ("APP_VERSION", "BUILD_ID", "WINDOWS_REVISION"))
    if not isinstance(app, str) or not re.fullmatch(r"\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?", app):
        raise ValueError("invalid APP_VERSION")
    if not isinstance(build, str) or not re.fullmatch(r"[0-9A-Za-z][0-9A-Za-z.-]{0,63}", build):
        raise ValueError("invalid BUILD_ID")
    if type(revision) is not int or not 0 <= revision <= 65535:
        raise ValueError("invalid WINDOWS_REVISION")
    numbers = tuple(int(value) for value in app.split("-", 1)[0].split(".")) + (revision,)
    if any(value > 65535 for value in numbers):
        raise ValueError("version exceeds Windows resource limits")
    return {"app_version": app, "build_id": build,
            "file_version": ".".join(str(value) for value in numbers),
            "file_tuple": numbers, "product_version": f"{app}+{build}"}


def render_resource(metadata):
    numbers = ", ".join(str(value) for value in metadata["file_tuple"])
    return f"""VSVersionInfo(
  ffi=FixedFileInfo(
    filevers=({numbers}),
    prodvers=({numbers}),
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable(
        '040904B0',
        [
          StringStruct('CompanyName', 'VoiceFlow contributors'),
          StringStruct('FileDescription', 'VoiceFlow offline dictation'),
          StringStruct('FileVersion', '{metadata['file_version']}'),
          StringStruct('InternalName', 'VoiceFlow'),
          StringStruct('LegalCopyright', 'Copyright (c) VoiceFlow contributors'),
          StringStruct('OriginalFilename', 'VoiceFlow.exe'),
          StringStruct('ProductName', 'VoiceFlow'),
          StringStruct('ProductVersion', '{metadata['product_version']}')
        ]
      )
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def sync_versions(root=ROOT, *, check=False, tag=None):
    root = Path(root)
    metadata = read_version(root)
    if tag is not None and tag != f"v{metadata['app_version']}":
        raise ValueError("release tag does not match src/version.py")
    include = (
        "; Generated by scripts/sync_version.py from src/version.py. Do not edit.\n"
        f'#define MyAppVersion "{metadata["app_version"]}"\n'
        f'#define MyAppBuildId "{metadata["build_id"]}"\n'
        f'#define MyAppFileVersion "{metadata["file_version"]}"\n'
    )
    outputs = {root / "installer" / "version.iss": include,
               root / "assets" / "version_info.txt": render_resource(metadata)}
    for path, content in outputs.items():
        actual = path.read_text(encoding="utf-8") if path.is_file() else None
        if actual == content:
            continue
        if check:
            raise ValueError(f"stale generated version metadata: {path.name}")
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8", newline="\n")
    return metadata


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--tag")
    args = parser.parse_args()
    metadata = sync_versions(check=args.check, tag=args.tag)
    print(f"Version metadata: {metadata['product_version']} / PE {metadata['file_version']}")


if __name__ == "__main__":
    main()
